const { chromium } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");
(async () => {
  const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
  const page = await browser.newPage({ viewport: { width: 1040, height: 680 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(String(error)));
  await page.goto("http://127.0.0.1:1420/illustrated-tree-preview.html?workspace&data=/preview/actual-data.json");
  await page.locator(".botanical-label.rank-root").waitFor();
  await page.waitForFunction(() => document.querySelector(".canvas-scale")?.textContent !== "100%");
  const out = path.resolve(__dirname, "../artifacts");
  fs.mkdirSync(out, { recursive: true });
  await page.screenshot({ path: path.join(out, "illustrated-tree-workspace.png") });
  const defaultLabels = await page.locator(".botanical-label").count();
  const initiallyHasDocument = await page.locator(".document").count() > 0;
  const rootTitle = await page.locator(".botanical-label.rank-root").textContent();
  await page.locator(".ux-collection-summary").first().click();
  await page.locator(".tree-knowledge-list button").last().click();
  await page.locator(".document-head h2").waitFor();
  const openedDocument = await page.locator(".document-head h2").innerText();
  const panelClosed = await page.locator(".tree-knowledge-panel").count() === 0;
  await page.getByRole("button", { name: "视图", exact: true }).click();
  await page.getByRole("menuitemcheckbox", { name: "传统树布局", exact: true }).click();
  await page.locator(".tree-edge").first().waitFor();
  const savedMode = await page.evaluate(() => localStorage.getItem("knowledge-tree-layout"));
  await page.getByRole("button", { name: "视图", exact: true }).click();
  await page.getByRole("menuitemcheckbox", { name: "插画知识树", exact: true }).click();
  await page.locator(".illustrated-tree").waitFor();
  const report = { defaultLabels, initiallyHasDocument, rootTitle, openedDocument, panelClosed, savedMode, errors };
  fs.writeFileSync(path.join(out, "illustrated-tree-workspace-check.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
  await browser.close();
  if (defaultLabels > 16 || initiallyHasDocument || !openedDocument || !panelClosed || savedMode !== "legacy" || errors.length) process.exitCode = 1;
})().catch((error) => { console.error(error); process.exitCode = 1; });
